#!/usr/bin/env python3
"""Generates the hue wheel behind the custom colour.

A theme attribute cannot be given a value computed at runtime, so the wheel has
to exist as ordinary resources: twenty four steps of fifteen degrees, and a
colour typed in as hex is snapped to the nearest one.

Tones are solved per hue for a contrast ratio rather than fixed in HSL, because
equal lightness is not equal darkness across hues: yellow and blue at the same
lightness are nowhere near the same. The ratios below are the source of truth
for the palette; edit them and rerun rather than editing the XML.

    python3 bin/gen_hue_palette.py
"""

import colorsys
import os

STEPS = 24
OUT = os.path.join(os.path.dirname(os.path.dirname(os.path.abspath(__file__))), "app/src/main/res")

WHITE = (255, 255, 255)
DARK = (18, 18, 18)


def rgb(hue, sat, light):
    r, g, b = colorsys.hls_to_rgb(hue / 360.0, light, sat)
    return tuple(round(c * 255) for c in (r, g, b))


def luminance(color):
    def channel(v):
        v /= 255.0
        return v / 12.92 if v <= 0.03928 else ((v + 0.055) / 1.055) ** 2.4

    return 0.2126 * channel(color[0]) + 0.7152 * channel(color[1]) + 0.0722 * channel(color[2])


def contrast(a, b):
    la, lb = luminance(a), luminance(b)
    if la < lb:
        la, lb = lb, la
    return (la + 0.05) / (lb + 0.05)


def against(hue, sat, reference, target, darker=True):
    """The tone whose contrast with reference is closest to target."""
    reference_luminance = luminance(reference)
    best = None
    for i in range(3000):
        light = 0.01 + i * 0.98 / 2999
        color = rgb(hue, sat, light)
        if darker != (luminance(color) < reference_luminance):
            continue
        distance = abs(contrast(color, reference) - target)
        if best is None or distance < best[0]:
            best = (distance, color)
    return best[1]


def balanced(hue, sat):
    """The tone that reads equally well on a light and on a dark background."""
    best = None
    for i in range(400):
        light = 0.15 + i * 0.6 / 399
        color = rgb(hue, sat, light)
        value = min(contrast(color, WHITE), contrast(color, DARK))
        if best is None or value > best[0]:
            best = (value, color)
    return best[1]


def hexadecimal(color):
    return "#%02X%02X%02X" % color


def step(index):
    hue = index * 360 // STEPS
    light_surface = rgb(hue, 0.06, 0.975)
    dark_surface = rgb(hue, 0.12, 0.075)
    return hue, {
        # The accents. Primary carries white text on the app bar, so it is held
        # at 5:1 against white on every step of the wheel. The accent is used as
        # text on the window background in both the light and the dark theme, so
        # it sits where those two contrasts are equal.
        "primary": against(hue, 0.40, WHITE, 5.0),
        "primary_dark": against(hue, 0.40, WHITE, 8.5),
        "accent": balanced(hue, 0.45),
        "material_100": against(hue, 0.35, WHITE, 1.35),
        "material_300": against(hue, 0.38, WHITE, 2.2),
        # The neutrals, barely tinted towards the hue, the way the wallpaper
        # palette tints them. Held in the day and night files separately.
        "surface": light_surface,
        "on_surface": against(hue, 0.20, light_surface, 15.0),
        "surface_variant": against(hue, 0.10, light_surface, 1.18),
        "on_surface_variant": against(hue, 0.14, light_surface, 7.0),
        "night_surface": dark_surface,
        "night_on_surface": against(hue, 0.10, dark_surface, 14.0, darker=False),
        "night_surface_variant": against(hue, 0.10, dark_surface, 1.9, darker=False),
        "night_on_surface_variant": against(hue, 0.08, dark_surface, 9.0, darker=False),
        # The hue as text on the window background. In the light theme that is
        # the accent and the primary themselves, which read well on a near white
        # surface; on a near black one they do not, so the night file holds a
        # tone lifted to 7:1 against it instead.
        "text_primary": against(hue, 0.40, WHITE, 5.0),
        "text_accent": balanced(hue, 0.45),
        "night_text_primary": against(hue, 0.45, dark_surface, 7.0, darker=False),
        "night_text_accent": against(hue, 0.45, dark_surface, 7.0, darker=False),
    }


GENERATED = "Generated by bin/gen_hue_palette.py; regenerate rather than hand-edit."

ACCENTS = ["primary", "primary_dark", "accent", "material_100", "material_300"]
NEUTRALS = ["surface", "on_surface", "surface_variant", "on_surface_variant",
            "text_primary", "text_accent"]


def write(path, body):
    with open(os.path.join(OUT, path), "w") as f:
        f.write('<?xml version="1.0" encoding="utf-8"?>\n<resources>\n\n')
        f.write("    <!-- %s -->\n" % GENERATED)
        f.write(body)
        f.write("\n</resources>\n")


def main():
    steps = [step(i) for i in range(STEPS)]

    body = ""
    for i, (hue, tones) in enumerate(steps):
        body += "\n    <!-- %d° -->\n" % hue
        for name in ACCENTS + NEUTRALS:
            body += '    <color name="hue_%d_%s">%s</color>\n' % (i, name, hexadecimal(tones[name]))
    write("values/colors_hue.xml", body)

    body = ""
    for i, (hue, tones) in enumerate(steps):
        body += "\n    <!-- %d° -->\n" % hue
        for name in NEUTRALS:
            body += '    <color name="hue_%d_%s">%s</color>\n' % (
                i, name, hexadecimal(tones["night_" + name]))
    write("values-night/colors_hue.xml", body)

    body = ""
    for i, _ in enumerate(steps):
        for base in ("Theme.SagerNet", "Theme.SagerNet.Dialog"):
            body += '\n    <style name="%s.Hue%d">\n' % (base, i)
            body += '        <item name="colorPrimary">@color/hue_%d_primary</item>\n' % i
            body += '        <item name="colorPrimaryDark">@color/hue_%d_primary_dark</item>\n' % i
            body += '        <item name="colorAccent">@color/hue_%d_accent</item>\n' % i
            body += '        <item name="colorMaterial100">@color/hue_%d_material_100</item>\n' % i
            body += '        <item name="colorMaterial300">@color/hue_%d_material_300</item>\n' % i
            body += '\n'
            body += '        <item name="android:colorBackground">@color/hue_%d_surface</item>\n' % i
            body += '        <item name="colorOnBackground">@color/hue_%d_on_surface</item>\n' % i
            body += '        <item name="colorSurface">@color/hue_%d_surface</item>\n' % i
            body += '        <item name="colorOnSurface">@color/hue_%d_on_surface</item>\n' % i
            body += '        <item name="colorSurfaceVariant">@color/hue_%d_surface_variant</item>\n' % i
            body += '        <item name="colorOnSurfaceVariant">@color/hue_%d_on_surface_variant</item>\n' % i
            body += '\n'
            # These four are the app's own attributes for "the themed colour,
            # used as text". They have to follow the background, so they name a
            # colour that the night file redefines rather than ?colorPrimary.
            body += '        <item name="primaryOrTextPrimary">@color/hue_%d_text_primary</item>\n' % i
            body += '        <item name="primaryOrTextSecondary">@color/hue_%d_text_primary</item>\n' % i
            body += '        <item name="accentOrTextPrimary">@color/hue_%d_text_accent</item>\n' % i
            body += '        <item name="accentOrTextSecondary">@color/hue_%d_text_accent</item>\n' % i
            body += "    </style>\n"
    write("values/themes_hue.xml", body)

    worst = min(contrast(t["primary"], WHITE) for _, t in steps)
    print("%d steps, worst primary contrast against white: %.2f" % (STEPS, worst))


if __name__ == "__main__":
    main()
